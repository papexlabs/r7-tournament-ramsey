#!/usr/bin/env python3
"""Generate R7lean/Data.lean from the adjacency matrices in ../data/.

Convention (the same as src/tourn.py, matrix_to_out): entry (i, j) of a
matrix file is 1 iff i -> j; the upper triangle (i < j) is authoritative.
This script checks that every matrix is square, 0/1, has a zero diagonal and
a lower triangle that is the complement of the upper one, so the Lean
definition `Tournament.ofUpper` (which reads only the upper triangle) agrees
with the whole file.

Each row i is stored as the bitmask sum_j M[i][j] * 2^j (the whole row).

usage: python3 -I tools/gen_data.py            (run from r7lean/)
"""
import hashlib
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]          # r7lean/
DATA = HERE.parent / "data"
OUT = HERE / "R7lean" / "Data.lean"


def read(name):
    path = DATA / name
    raw = path.read_bytes()
    rows = [l.split() for l in raw.decode().splitlines() if l.split()]
    n = len(rows)
    for i, r in enumerate(rows):
        assert len(r) == n, f"{name}: row {i} has length {len(r)} != {n}"
        for j, c in enumerate(r):
            assert c in ("0", "1"), f"{name}: entry ({i},{j}) = {c!r}"
            if i == j:
                assert c == "0", f"{name}: nonzero diagonal at {i}"
            elif i < j:
                assert (c == "1") != (rows[j][i] == "1"), f"{name}: ({i},{j}) and ({j},{i}) inconsistent"
    masks = [sum(1 << j for j, c in enumerate(r) if c == "1") for r in rows]
    return n, masks, hashlib.sha256(raw).hexdigest()


def vec(masks, first="  ofRows ", indent="    "):
    """`first[m0, m1, ...]`, wrapped so that no line exceeds 100 characters."""
    lines, cur = [], first + "["
    for k, m in enumerate(masks):
        tok = str(m) + ("]" if k == len(masks) - 1 else ",")
        if len(cur) + 1 + len(tok) > 100:
            lines.append(cur)
            cur = indent + tok
        else:
            cur += tok if cur.endswith("[") else " " + tok
    lines.append(cur)
    return "\n".join(lines)


L23 = "ABCDEFGHIJKLMNOPQRSTUVWXY"
L24 = "ABCDE"

out = []
w = out.append
w("import R7lean.Tournament")
w("import Mathlib.Data.Fin.VecNotation")
w("")
w("/-!")
w("# The named tournaments (generated)")
w("")
w("GENERATED by `tools/gen_data.py` from the matrices in `../data/`; do not edit by hand.")
w("")
w("Convention (as in `src/tourn.py`): entry `(i, j)` of a matrix file is `1` iff `i → j`.")
w("Row `i` is stored as the bitmask `∑ⱼ M[i][j] * 2^j` and the tournament is")
w("`Tournament.ofRows` (= `ofUpper`), which reads only the upper triangle; the generator checked that")
w("each file is a 0/1 matrix with zero diagonal whose lower triangle is the complement of")
w("the upper one, so the definition agrees with the whole file. The sha256 of each source")
w("file is recorded next to its definition.")
w("")
w("`ST26` and `ST25` are not separate files: they are `ST27` minus vertex `0`, and `ST27`")
w("minus vertices `0, 1`, exactly as in `scripts/stage4_instances.py` (`structure`, the")
w("reference for `ST25`/`ST26`) and `data/ST26-p-TT5.txt` (whose first 26 rows are `ST27`")
w("minus vertex `0`).")
w("-/")
w("")
w("namespace R7")
w("")
w("open Tournament")
w("")


def small(name, lean, doc, abbrev=False):
    n, masks, h = read(name)
    kw = "abbrev" if abbrev else "def"
    w(f"/-- {doc}")
    w(f"Source: `data/{name}`, sha256")
    w(f"`{h}`. -/")
    w(f"{kw} {lean} : Tournament (Fin {n}) :=")
    w(vec(masks))
    w("")
    if not abbrev:
        w(f"instance : DecidableRel {lean}.beats := decOfRows _")
        w("")
    return n


small("H6.txt", "H6", "`H₆ = TT₃ ⇒ C₃` (vertices `0,1,2` transitive and beating `3,4,5`; `3 → 4 → 5 → 3`).", abbrev=True)
small("W7.txt", "W7", "`W₇ = G₇ = TT₂ ⇒ RT₅` (`0, 1` beat everything; on `2..6`, `i → i+1, i+2` mod 5).", abbrev=True)
small("Y8.txt", "Y8", "NMH's 8-vertex tournament `Y₈` (15 three-cycles; not isomorphic to its reversal).")
small("O21star.txt", "O21s", "The exceptional TT₆-free tournament `O21*` on 21 vertices.")
small("ST27.txt", "ST27", "`ST₂₇`: the Paley tournament on GF(27), as constructed by `src/tourn.py` (`st27`).")
w("/-- `ST₂₆ = ST₂₇ - {0}` (vertex `i` is vertex `i + 1` of `ST₂₇`); this is exactly the")
w("`X` block of `data/ST26-p-TT5.txt`. -/")
w("def ST26 : Tournament (Fin 26) := ST27.comap (Fin.succEmb 26)")
w("")
w("instance : DecidableRel ST26.beats := decComap _ _")
w("")
w("/-- `ST₂₅ = ST₂₇ - {0, 1}` (vertex `i` is vertex `i + 2` of `ST₂₇`), the reference used by")
w("`scripts/stage4_instances.py` for the `X` block of `ST25-p-H6` and `ST25-p-W7`. -/")
w("def ST25 : Tournament (Fin 25) := ST27.comap (Fin.natAddEmb 2)")
w("")
w("instance : DecidableRel ST25.beats := decComap _ _")
w("")
for L in L24:
    small(f"I24_{L}.txt", f"I24{L}", f"NMH's TT₆-free tournament `24{L}` (a 24-vertex subtournament of `ST₂₇`).")
for L in L23:
    kind = ("a 23-vertex subtournament of `ST₂₇`" if L <= "V" else
            "doubly regular, from NMH's repository" if L in "WX" else
            "the quadratic-residue tournament on `ℤ/23`")
    small(f"I23_{L}.txt", f"I23{L}", f"NMH's TT₆-free tournament `23{L}` ({kind}).")
w("/-- The five TT₆-free tournaments on 24 vertices, `I24 0 = I24A`, …, `I24 4 = I24E`. -/")
w("def I24 : Fin 5 → Tournament (Fin 24) :=")
w("  ![" + ", ".join(f"I24{L}" for L in L24) + "]")
w("")
w("/-- The 25 TT₆-free tournaments on 23 vertices, `I23 0 = I23A`, …, `I23 24 = I23Y`. -/")
w("def I23 : Fin 25 → Tournament (Fin 23) :=")
w("  ![" + ", ".join(f"I23{L}" for L in L23[:12]) + ",")
w("    " + ", ".join(f"I23{L}" for L in L23[12:]) + "]")
w("")
w("end R7")
OUT.write_text("\n".join(out) + "\n")
print(f"wrote {OUT}")
